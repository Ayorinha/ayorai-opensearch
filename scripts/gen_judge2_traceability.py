#!/usr/bin/env python3
"""Generate the Judge 2 rule-to-test-to-Golden traceability matrix."""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
MAPPING = ROOT / "docs" / "judge2" / "traceability-map.json"
OUTPUT = ROOT / "docs" / "judge2" / "TRACEABILITY.md"
GOLDENS = (
    ROOT / "evals" / "golden" / "v0-r2.jsonl",
    ROOT / "evals" / "golden" / "v0.1-r2.jsonl",
)
EXPECTED_IDS = [
    "G1", "G2", "E1", "E2", "E3", "A1", "A2", "A3", "A4",
    "R0", "R1", "R2", "R3", "K1", "K2", "K3", "K4", "K5",
]


def read_golden(path: Path) -> list[dict[str, Any]]:
    return [
        json.loads(line)
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def case_matches(case: dict[str, Any], selector: str) -> bool:
    claims = case.get("expected_claims", [])
    if selector == "none":
        return False
    if selector == "abstained":
        return case.get("expected_decision_state") == "ABSTAINED"
    kind, value = selector.split(":", 1)
    if kind == "atomic":
        return any(claim.get("verdict") == value for claim in claims)
    if kind == "robustness":
        return case.get("expected_robustness") == value or any(
            claim.get("robustness") == value for claim in claims
        )
    if kind == "composite":
        return len(claims) > 1 and case.get("expected_verdict") == value
    raise ValueError(f"unknown Golden selector: {selector}")


def load_and_validate_rules() -> list[dict[str, Any]]:
    rules = json.loads(MAPPING.read_text(encoding="utf-8"))
    ids = [rule["id"] for rule in rules]
    if ids != EXPECTED_IDS or len(ids) != len(set(ids)):
        raise SystemExit("traceability rule IDs do not match the normative rule set")

    missing: list[str] = []
    for rule in rules:
        if not rule.get("tests"):
            missing.append(f"{rule['id']}: no test mapped")
            continue
        for test_path, name in rule["tests"]:
            path = ROOT / test_path
            pattern = rf"^\s*def\s+{re.escape(name)}\s*\("
            if not path.is_file() or not re.search(
                pattern, path.read_text(encoding="utf-8"), re.MULTILINE
            ):
                missing.append(f"{rule['id']}: missing {test_path}::{name}")
    if missing:
        raise SystemExit(
            "traceability rules without executable tests:\n" + "\n".join(missing)
        )
    return rules


def render() -> str:
    rules = load_and_validate_rules()
    datasets = [(path.name, read_golden(path)) for path in GOLDENS]
    lines = [
        "# Judge 2.0.0 — Traceability (generated)",
        "",
        "Generated by python scripts/gen_judge2_traceability.py. Do not edit manually.",
        "",
        "Source: ADR-009 §§3–9. Test identifiers are checked against the test files; a rule without an existing test fails generation/check mode.",
        "",
        "| Rule | Normative behavior | Tests | Golden r2 cases |",
        "|---|---|---|---|",
    ]
    for rule in rules:
        test_text = "<br>".join(
            f"{test_path}::{name}" for test_path, name in rule["tests"]
        )
        golden_text: list[str] = []
        for name, cases in datasets:
            ids = [
                str(case.get("id", "?"))
                for case in cases
                if case_matches(case, rule["selector"])
            ]
            if ids:
                golden_text.append(f"{name}: {', '.join(ids)}")
        golden = "<br>".join(golden_text) or rule["note"] or "—"
        lines.append(
            f"| **{rule['id']}** | {rule['meaning']} | {test_text} | {golden} |"
        )
    lines.extend(
        [
            "",
            "## Coverage notes",
            "",
            "- Golden v0-r2 and v0.1-r2 have the same case IDs; each dataset is listed independently.",
            "- E1–E3 are tested at the evidence-gate layer; current Golden r2 records do not carry raw offsets, excerpts, hashes, or stance edges, so no direct Golden case is claimed for those rules.",
            "- G1 negative inputs and composite K1/K4/K5 are covered by dedicated negative tests or the exhaustive composite truth table where no direct Golden case exists.",
            "- This matrix records test-to-rule coverage; it does not claim that tests prove factual correctness outside the declared scope.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail unless the committed document matches generated bytes",
    )
    args = parser.parse_args()
    generated = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(
                "docs/judge2/TRACEABILITY.md is stale; run "
                "python scripts/gen_judge2_traceability.py",
                file=sys.stderr,
            )
            return 1
        print("Judge 2 traceability parity: OK")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"generated {OUTPUT.relative_to(ROOT)} with {len(EXPECTED_IDS)} rules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
