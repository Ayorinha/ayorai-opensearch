#!/usr/bin/env python3
"""Generate the committed Judge 2.0.0 decision truth table deterministically."""
from __future__ import annotations

import sys
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ayorai_attractor.verification.judge2 import load_rules  # noqa: E402
from ayorai_attractor.verification.judge2.adjudication import (  # noqa: E402
    AtomicDecision,
    _atomic_verdict,
)

VERDICTS = ("SUPPORTED", "PARTIALLY_SUPPORTED", "REFUTED", "UNVERIFIED", "CONFLICTING")


def _atom_decision(index: int, verdict: str) -> AtomicDecision:
    return AtomicDecision(
        atom_id=f"atom-{index}",
        verdict=verdict,
        robustness="R0",
        robustness_support="R0",
        robustness_contradiction="R0",
        support_clusters=0,
        contradiction_clusters=0,
        rule_id="2.0.0/A1",
    )



def _composite_from_contract(rules: dict[str, object], decisions: list[AtomicDecision]) -> tuple[str, str]:
    by_id = {rule["id"]: rule for rule in rules["composite_rules"]}  # type: ignore[index]
    verdicts = [item.verdict for item in decisions]
    for rule_id in rules["composite_precedence"]:  # type: ignore[index]
        rule = by_id[rule_id]
        predicate = rule["when"]
        if predicate == "any_atom_REFUTED":
            matched = "REFUTED" in verdicts
        elif predicate == "otherwise_any_atom_CONFLICTING":
            matched = "CONFLICTING" in verdicts
        elif predicate == "all_atoms_SUPPORTED":
            matched = all(value == "SUPPORTED" for value in verdicts)
        elif predicate == "otherwise_any_atom_SUPPORTED":
            matched = "SUPPORTED" in verdicts
        elif predicate == "otherwise":
            matched = True
        else:
            raise ValueError(f"unsupported composite predicate: {predicate}")
        if matched:
            return str(rule["verdict"]), f"2.0.0/{rule_id}"
    raise ValueError("composite rules did not produce a decision")


def render() -> str:
    rules, digest = load_rules()
    lines = [
        "# Judge 2.0.0 — Decision Truth Table",
        "",
        "Generated by `python scripts/gen_truth_table.py`. Do not edit manually.",
        "",
        f"- Contract SHA-256: `{digest}`",
        "- Decision authority: deterministic contract rules only.",
        "- Input restriction: only evidence admitted by the item-2.2 gates may contribute.",
        "- Atomic table covers 12 combinations: S∈{0..3}, C∈{0..2}.",
        "- Provenance variants are tested under T1.",
        "- Exhaustive composite rows cover every ordered verdict tuple for 1–4 atoms (780 rows).",
        "",
        "## Atomic rules (A1–A4)",
        "",
        "| Support clusters | Contradiction clusters | Verdict | Rule |",
        "|---:|---:|---|---|",
    ]
    for supports, contradicts in product(range(4), range(3)):
        verdict, rule_id = _atomic_verdict(rules, supports, contradicts)
        lines.append(f"| {supports} | {contradicts} | {verdict} | 2.0.0/{rule_id} |")
    lines.extend([
        "",
        "## Composite rules (K1–K5), exhaustive through n=4",
        "",
        "| n | Atom verdict tuple | Composite verdict | Rule |",
        "|---:|---|---|---|",
    ])
    for size in range(1, 5):
        for values in product(VERDICTS, repeat=size):
            decisions = [_atom_decision(index, value) for index, value in enumerate(values)]
            verdict, rule_id = _composite_from_contract(rules, decisions)
            tuple_text = ", ".join(values)
            lines.append(
                f"| {size} | `({tuple_text})` | {verdict} | {rule_id} |"
            )
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    print(render(), end="")
